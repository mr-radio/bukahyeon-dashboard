import * as a from '../scripts/update-runner.mjs';
import assert from 'node:assert/strict';
let checks = 0;
const equal = (x,y) => { assert.deepEqual(x,y); checks++; };
const rejects = f => { assert.throws(f); checks++; };
const init = () => a.createProgress({date:'2026-11-26',cutoff:'2026-11-25T23:59:59+09:00',chatDates:['2026-11-25']});
let p=init();
equal(a.nextTask(p,'run-a'),'news');
p=a.recordStep(p,'news',{scanStatus:'partial',writeStatus:'committed',commitSha:'abc',reason:'One query reviewed',nextAction:'Next query',counts:{added:1,reviewed:1}});
equal(a.nextTask(p,'run-b'),'news');
rejects(()=>a.recordStep(p,'cafe',{scanStatus:'partial',writeStatus:'no_change',reason:'blocked',nextAction:'retry'}));
p=a.recordAttempt(p,'news',{runId:'run-a',routeKey:'query-1:page-1:browser',outcome:'rate_limited'});
equal(a.nextTask(p,'run-a'),'blogNews');
rejects(()=>a.recordAttempt(p,'news',{runId:'run-a',routeKey:'query-1:page-1:browser',outcome:'failed'}));
equal(a.classifyFetch({httpStatus:200}),'shell_or_incomplete');
equal(a.classifyFetch({httpStatus:429}),'rate_limited');
equal(a.classifyFetch({httpStatus:403}),'access_denied');
equal(a.classifyFetch({httpStatus:200,explicitEmpty:true}),'empty_confirmed');
equal(a.canonicalKey('https://m.blog.naver.com/PostView.naver?blogId=a&logNo=123&navType=by'),a.canonicalKey('https://blog.naver.com/a/123'));
equal(a.canonicalKey('https://n.news.naver.com/mnews/article/001/123?sid=101'),a.canonicalKey('https://n.news.naver.com/article/001/123'));
const existing=[{url:'https://blog.naver.com/a/123',title:'old',date:'2026-11-24'}];
const merged=a.mergeRecords(existing,[{url:'https://m.blog.naver.com/a/123',title:'same',date:'2026-11-24'},{url:'https://blog.naver.com/a/124',title:'new',date:'2026-11-25'}]);
equal(merged.added.length,1); equal(merged.records.length,2); equal(existing[0].title,'old');
rejects(()=>a.validateBatch([{title:'future',url:'https://blog.naver.com/a/125',date:'2026-11-26'}],{cutoffDate:'2026-11-25',reviewed:true}));
rejects(()=>a.validateBatch([{title:'wrong',url:'https://blog.naver.com/a/125',date:'2026-11-25',categoryNo:1}],{cutoffDate:'2026-11-25',reviewed:true,categoryNo:47}));
rejects(()=>a.validateBatch([],{cutoffDate:'2026-11-25',reviewed:false}));
rejects(()=>a.validateBatch([{title:'invalid',url:'https://blog.naver.com/a/125',date:'2026-02-30'}],{cutoffDate:'2026-11-25',reviewed:true}));
rejects(()=>a.recordStep(init(),'news',{scanStatus:'complete',writeStatus:'committed',counts:{added:0}}));
let ready=init();
ready=a.recordStep(ready,'blogNews',{writeStatus:'ready'});
equal(a.nextTask(ready,'new-run'),'blogNews');
let good=init();
for (let i=1;i<=3;i++) good=a.recordAttempt(good,'news',{runId:'same-run',routeKey:'query:page-'+i,outcome:'candidate'});
equal(a.nextTask(good,'same-run'),'news');
let blocked=init();
blocked=a.recordStep(blocked,'news',{scanStatus:'blocked',reason:'cooldown',nextAction:'wait',retryAfter:'2026-11-27T00:00:00Z'});
equal(a.nextTask(blocked,'retry','2026-11-26T00:00:00Z'),'blogNews');
console.log(checks + ' assertions passed');
